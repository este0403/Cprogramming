#include <stdio.h>

int main(void)
{
    int* ptr = (int*)125;   // ① 정수 125를 int형 포인터로 강제형변환
    *ptr = 10;              // 125번지에 10을 저장 시도 -> 접근 권한 없는 메모리
    printf("%d\n", *ptr);

    return 0;
}

/* 결과:
실행 중단됨 (Segmentation Fault)
*/

/*
[설명]

① 강제형변환이 사용된 이유
125는 원래 int(정수) 상수이다. 그런데 ptr은 int*(포인터) 타입이므로
정수 값을 포인터 변수에 그대로 대입하면 타입이 일치하지 않아
컴파일 경고/오류가 발생한다. 그래서 (int*)125 처럼 강제형변환을 하여
"125라는 정수를 int형 포인터로 취급하겠다"는 의미로 명시적으로 바꿔준 것이다.
즉, 125라는 값을 "주소"로 해석하도록 타입만 맞춰준 것이지,
실제로 유효한 메모리 주소라는 뜻은 아니다.

[실행 중 오류가 발생하는 이유]
- 주소 125번지는 현재 프로그램(운영체제)이 이 프로세스에게 할당해준
  메모리 영역이 아니다. 즉, 우리 프로그램이 접근할 권한이 없는
  임의의(또는 존재하지 않는) 메모리 위치이다.
- *ptr = 10; 은 "포인터 ptr이 가리키는 주소에 10을 써라"는 명령인데,
  이는 운영체제가 보호하고 있는(우리 프로세스 소유가 아닌) 메모리 영역에
  강제로 쓰기를 시도하는 것이다.
- 이런 접근은 운영체제의 메모리 보호 기능에 의해 즉시 감지되어
  세그멘테이션 오류(Segmentation Fault) 형태로 프로그램이 강제 종료된다.
- 결론적으로 포인터에는 반드시 &변수처럼 실제로 유효하고 우리가
  소유권을 가진 메모리 주소만 대입해서 사용해야 하며, 임의의 정수 값을
  주소로 사용하는 것은 위험한 코드이다.
*/
