/*
[변형한 문제]
int형 변수 num1과 num2를 선언과 동시에 각각 8과 15로 초기화하고,
int형 포인터 변수 pa와 pb를 선언하여 각각 num1과 num2를 가리키게 하자.
이 상태에서 포인터 변수 pa와 pb를 이용해서 num1의 값을 3배로 만들고,
num2의 값을 2배로 만들자.
이제 두 포인터 변수 pa와 pb가 가리키는 대상을 서로 바꾸자.
즉, 포인터 변수 pa가 num2를 가리키게 하고, 포인터 변수 pb가 num1을
가리키게 하자. 그리고 마지막으로 pa와 pb가 각각 가리키는 변수에
저장된 값을 모두 출력하자.

(원본 문제와의 차이점 : 초기값 변경, 증감연산 대신 곱셈연산 사용,
 최종 출력 대상을 ptr2 하나가 아닌 pa/pb 두 개 모두로 변경)
*/

#include <stdio.h>

int main(void)
{
    int num1 = 8, num2 = 15;
    int* pa = &num1;   // pa는 num1을 가리킴
    int* pb = &num2;   // pb는 num2를 가리킴
    int* temp;

    *pa = (*pa) * 3;    // num1 = 8 * 3 = 24
    *pb = (*pb) * 2;    // num2 = 15 * 2 = 30

    // pa와 pb가 가리키는 대상을 서로 교환
    temp = pa;
    pa = pb;
    pb = temp;

    printf("pa가 가리키는 값 : %d\n", *pa);  // num2였던 값 -> 30
    printf("pb가 가리키는 값 : %d\n", *pb);  // num1이었던 값 -> 24

    return 0;
}

/* 결과:
pa가 가리키는 값 : 30
pb가 가리키는 값 : 24
*/
