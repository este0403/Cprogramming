/*
[1] 증감연산자 a++, ++a의 차이

- a++ (후위 증가) : 현재 a의 값을 먼저 "사용"한 뒤에 a의 값을 1 증가시킨다.
                    즉, 식 안에서는 증가되기 전의 값이 사용된다.
- ++a (전위 증가) : a의 값을 먼저 1 증가시킨 뒤에 그 증가된 값을 "사용"한다.
                    즉, 식 안에서는 이미 증가된 값이 사용된다.

  예) int a = 5, b;
      b = a++;   // b에는 증가 전 값인 5가 저장되고, 이후 a는 6이 됨
      b = ++a;   // a가 먼저 7이 된 뒤, 그 값 7이 b에 저장됨

  단독으로 한 줄에 쓰일 때(a++; 또는 ++a;)는 결과적으로 둘 다
  a의 값을 1 증가시키는 것으로 동일하지만, 다른 수식/함수 인자 안에서
  함께 사용될 때는 "언제 증가된 값이 쓰이느냐"가 달라진다.


[2] 아래 코드의 문제점

    int a[] = { 10, 20, 30 }, i, sum = 0;
    for (i = 0; i < 3; i++)
        sum += *a++;

  여기서 a는 배열명이다. 배열명은 "배열 첫번째 요소의 주소"를 나타내는
  포인터 상수(변수가 아님)이므로, a++ 처럼 그 값을 변경(증가)시키는
  연산은 허용되지 않는다. 즉, 이 코드는
  "lvalue required as increment operand" 같은 컴파일 오류가 발생하여
  컴파일 자체가 되지 않는다.

  [해결 방법]
  배열명 a 대신, a의 주소값을 저장한 포인터 "변수"를 새로 선언하여
  그 포인터 변수를 증가시키면 된다. 포인터 변수는 상수가 아니라
  변수이므로 자유롭게 값을 변경(증가/감소)할 수 있다.
*/

#include <stdio.h>

int main(void)
{
    int a[] = { 10, 20, 30 }, i, sum = 0;
    int* p = a;   // 배열명 a 대신 사용할 포인터 변수 p (a의 주소를 저장)

    for (i = 0; i < 3; i++)
        sum += *p++;   // p는 변수이므로 증가 연산이 가능함

    printf("sum:%d\n", sum);

    return 0;
}

/* 결과:
sum:60
*/
