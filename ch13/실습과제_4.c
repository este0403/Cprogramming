/*
[변형한 문제]
길이가 5인 double형 배열 arr을 선언하고, 키보드로부터 5개의 실수를
입력받아 초기값으로 저장한다(저장할 때도 포인터 변수를 증가시키는
연산을 이용). 그 다음 배열의 첫번째 요소를 가리키는 포인터 변수 ptr을
선언하고, ptr에 저장된 값을 증가시키는 형태의 연산을 기반으로
배열요소에 접근하면서 모든 배열요소의 값을 2씩 증가시키고, 정상적으로
증가가 이뤄졌는지 확인한다.
*/

#include <stdio.h>

int main(void)
{
    double arr[5];
    double* ptr = arr;   // 배열의 첫번째 요소를 가리키는 포인터 변수 ptr
    int i;

    // 키보드로부터 5개의 실수를 입력받아 저장 (포인터 증가연산 이용)
    for (i = 0; i < 5; i++)
    {
        printf("실수를 입력하시오: ");
        scanf("%lf", ptr);   // ptr이 가리키는 위치에 입력값 저장
        ptr++;                // 다음 요소를 가리키도록 이동
    }

    ptr = arr;   // ptr을 다시 배열의 첫번째 요소로 되돌림
    printf("증가 전 배열 값: ");
    for (i = 0; i < 5; i++)
    {
        printf("%.1f ", *ptr);
        ptr++;
    }
    printf("\n");

    ptr = arr;   // 값 증가를 위해 ptr을 다시 첫번째 요소로 되돌림
    for (i = 0; i < 5; i++)
    {
        *ptr += 2;   // ptr이 가리키는 현재 요소에 2를 더함
        ptr++;       // 다음 요소로 이동
    }

    ptr = arr;   // 확인을 위해 ptr을 다시 첫번째 요소로 되돌림
    printf("증가 후 배열 값: ");
    for (i = 0; i < 5; i++)
    {
        printf("%.1f ", *ptr);
        ptr++;
    }
    printf("\n");

    return 0;
}

