#include <stdio.h>

// 실행결과를 분석하면 x<-y, y<-z, z<-x 순서로 값이 한 칸씩 회전(교환)됨
// (x=10,y=20,z=30 -> x=20,y=30,z=10)
// 세 변수를 모두 다른 함수(swap)에서 실제로 바꾸려면 반드시
// 주소에 의한 호출(포인터)을 사용해야 함 -> 값에 의한 호출로는
// main의 지역변수 x,y,z를 변경할 수 없기 때문
void swap(int* px, int* py, int* pz);

int main(void)
{
    int x, y, z;

    printf("정수x를 입력 하시오:");
    scanf("%d", &x);
    printf("정수y를 입력 하시오:");
    scanf("%d", &y);
    printf("정수z를 입력 하시오:");
    scanf("%d", &z);

    printf("swap함수 호출 전 x=%d, y=%d, z=%d\n", x, y, z);

    swap(&x, &y, &z);   // x,y,z의 주소를 전달 (주소에 의한 호출)

    printf("swap함수 호출 후 x=%d, y=%d, z=%d\n", x, y, z);

    return 0;
}

// 세 정수를 회전시키는 함수 (x<-y, y<-z, z<-x)
//
// [시간 순서에 따른 메모리 변화] (24페이지 그림 참고)
// 1) 호출 전         : x=10  y=20  z=30
// 2) tmp=*px 실행 직후 : tmp=10 (x값을 임시로 보관)
// 3) *px=*py 실행 후   : x=20 (y값을 x자리로 이동)
// 4) *py=*pz 실행 후   : y=30 (z값을 y자리로 이동)
// 5) *pz=tmp 실행 후   : z=10 (처음 보관해둔 x값을 z자리로 이동)
// -> 최종 : x=20  y=30  z=10
void swap(int* px, int* py, int* pz)
{
    int tmp;

    tmp = *px;  // x의 원래 값을 임시로 저장 (곧 덮어쓰일 값이므로 보관)
    *px = *py;  // x자리에 y값을 넣음
    *py = *pz;  // y자리에 z값을 넣음
    *pz = tmp;  // z자리에 처음 보관했던 x값을 넣음
}

