// 길이가 10인 배열에 정수 10개를 입력받은 뒤,
// 홀수를 먼저 출력하고 그 다음에 짝수를 출력한다.
// 홀수만 출력하는 함수(Hol)와 짝수만 출력하는 함수(Zzack)를 각각 정의하고
// main 함수에서 두 함수를 호출한다.

#include <stdio.h>

void Hol(int n1[], int len);     // 배열 안의 홀수만 출력
void Zzack(int n1[], int len);   // 배열 안의 짝수만 출력

int main(void)
{
    int arr[10];
    int len = sizeof(arr) / sizeof(int);   // 배열 원소 개수 = 전체 크기 / 원소 1개의 크기
    int i;

    printf("총 10개의 숫자 입력\n");
    for (i = 0; i < len; i++)
    {
        printf("입력: ");
        scanf("%d", &arr[i]);
    }

    Hol(arr, len);     // 배열명(시작 주소)과 길이를 전달
    Zzack(arr, len);

    return 0;
}

// 홀수만 골라 출력하는 함수
void Hol(int n1[], int len)
{
    int i;
    int count = 0;     // 지금까지 출력한 개수 (쉼표 출력 여부 판단용)

    printf("홀수 출력: ");
    for (i = 0; i < len; i++)
    {
        if (n1[i] % 2 != 0)          // 2로 나눈 나머지가 0이 아니면 홀수 (음수도 처리 가능)
        {
            if (count > 0)
                printf(", ");        // 첫 번째 값 앞에는 쉼표를 붙이지 않는다.
            printf("%d", n1[i]);
            count++;
        }
    }
    printf("\n");
}

// 짝수만 골라 출력하는 함수
void Zzack(int n1[], int len)
{
    int i;
    int count = 0;

    printf("짝수 출력: ");
    for (i = 0; i < len; i++)
    {
        if (n1[i] % 2 == 0)          // 2로 나눈 나머지가 0이면 짝수 (0도 짝수)
        {
            if (count > 0)
                printf(", ");
            printf("%d", n1[i]);
            count++;
        }
    }
    printf("\n");
}

