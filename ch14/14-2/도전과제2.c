// 사용자로부터 10진수 형태로 정수를 하나 입력받은 다음,
// 이를 2진수로 변환해서 출력한다.
//
// [변환 방법]
// 10진수를 2로 계속 나누면서 나머지를 차례로 저장하고,
// 몫이 0이 되면 멈춘 뒤 저장한 나머지를 거꾸로(마지막 것부터) 읽는다.
// 예) 12 -> 12%2=0, 6%2=0, 3%2=1, 1%2=1 -> 거꾸로 읽으면 1100

#include <stdio.h>

int main(void)
{
    int num;          // 입력받은 10진수
    int bin[100];     // 나머지(2진수의 각 자리)를 저장할 배열
    int i = 0;        // 저장한 자리 수
    int j;

    printf("10진수 정수 입력: ");
    scanf("%d", &num);

    if (num < 0)      // 이 프로그램은 0 이상의 정수만 변환한다.
    {
        printf("0 이상의 정수를 입력하세요.\n");
        return 0;
    }

    if (num == 0)     // 0은 while문이 실행되지 않으므로 따로 처리
    {
        printf("0\n");
        return 0;
    }

    while (num > 0)
    {
        bin[i] = num % 2;   // 2로 나눈 나머지를 저장 (가장 낮은 자리부터 나온다)
        num /= 2;           // 몫으로 계속 진행
        i++;
    }

    // 나머지는 낮은 자리부터 저장되었으므로 마지막 인덱스부터 거꾸로 출력
    for (j = i - 1; j >= 0; j--)
        printf("%d", bin[j]);
    printf("\n");

    return 0;
}

/* 실행 결과
10진수 정수 입력: 12<엔터>
1100
*/
