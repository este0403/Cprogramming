// 교재 15장 도전 3
// 길이가 10인 배열에 정수 10개를 입력받는다.
// 입력받은 숫자가 홀수이면 배열의 앞에서부터 채워 나가고,
// 짝수이면 배열의 뒤에서부터 채워 나간다.
// 예) 1, 2, 3, ..., 10을 입력하면 배열에는 [1, 3, 5, 7, 9, 10, 8, 6, 4, 2]가 저장된다.

#include <stdio.h>

int main(void)
{
    int arr[10];
    int len = sizeof(arr) / sizeof(int);   // 배열 원소 개수
    int front = 0;          // 홀수를 저장할 위치 (앞에서 뒤로 이동)
    int back = len - 1;     // 짝수를 저장할 위치 (뒤에서 앞으로 이동)
    int num, i;

    printf("총 10개의 숫자 입력\n");
    for (i = 0; i < len; i++)
    {
        printf("입력: ");
        scanf("%d", &num);

        if (num % 2 != 0)
        {
            arr[front] = num;   // 홀수는 앞쪽 빈 칸에 저장
            front++;            // 다음 홀수는 한 칸 뒤에 저장
        }
        else
        {
            arr[back] = num;    // 짝수는 뒤쪽 빈 칸에 저장
            back--;             // 다음 짝수는 한 칸 앞에 저장
        }
    }

    // 입력이 총 10개이므로 front와 back은 서로 겹치지 않고 배열이 정확히 채워진다.
    printf("배열 요소의 출력 : ");
    for (i = 0; i < len; i++)
        printf("%d ", arr[i]);
    printf("\n");

    return 0;
}

