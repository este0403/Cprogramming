#include <stdio.h>

// 배열의 최대값을 구해 반환하는 함수 선언
// 배열은 주소(시작 위치)로만 전달되므로 매개변수를 포인터로 선언한다.
int get_max(int* array, int n);

int main(void)
{
    int data[5];      // 입력받은 정수 5개를 저장할 배열
    int i, max;

    printf("정수5개를 입력 하시오.\n");
    for (i = 0; i < 5; i++)
    {
        scanf("%d", &data[i]);   // 각 배열 원소에 입력 (원소의 주소 &data[i] 전달)
    }

    max = get_max(data, 5);      // 배열명(시작 주소)과 원소 개수를 전달
    printf("최대값은 %d입니다.\n", max);

    return 0;
}

// 최대값을 구하는 함수 정의
int get_max(int* array, int n)
{
    int i, max;

    max = *array;                // 첫 번째 원소(array[0])를 일단 최대값으로 가정
    for (i = 1; i < n; i++)      // 두 번째 원소부터 끝까지 차례로 비교
    {
        if (*(array + i) > max)  // *(array+i)는 array[i]와 같다.
            max = *(array + i);  // 더 큰 값이 나오면 최대값을 갱신
    }

    return max;                  // 최종 최대값 반환
}

