// 라고 되어 있는 점에서, num 변수의 값을 100배로 만드는 함수를
// (1)값에 의한 호출과 (2)주소에 의한 호출 두 가지 방식으로 각각
// 작성하여 그 차이를 비교하는 문제로 해석하여 구현하였습니다.
// 만약 교재의 실제 지문과 다르다면 말씀해 주시면 수정하겠습니다.
#include <stdio.h>

void multiply100_byValue(int num);     // 값에 의한 호출 방식
void multiply100_byAddress(int* pnum); // 주소에 의한 호출 방식

int main(void)
{
    int num;

    printf("정수를 입력하시오:");
    scanf("%d", &num);

    printf("\n[값에 의한 호출]\n");
    printf("호출 전 num=%d\n", num);
    multiply100_byValue(num);
    printf("호출 후 num=%d (변경되지 않음)\n", num);

    printf("\n[주소에 의한 호출]\n");
    printf("호출 전 num=%d\n", num);
    multiply100_byAddress(&num);   // num의 주소를 전달
    printf("호출 후 num=%d (100배로 변경됨)\n", num);

    return 0;
}

// (1) 값에 의한 호출 : num의 "값"만 복사되어 지역변수 num에 저장됨
// -> 함수 안에서 아무리 값을 바꿔도 main의 num에는 영향을 주지 못함
void multiply100_byValue(int num)
{
    num = num * 100;   // 이 함수만의 지역변수 num을 바꾸는 것일 뿐
}

// (2) 주소에 의한 호출 : num이 저장된 메모리의 "주소"를 전달받음
// -> 포인터 *pnum을 통해 main의 num이 저장된 공간을 직접 수정함
void multiply100_byAddress(int* pnum)
{
    *pnum = *pnum * 100;   // main의 num 값 자체가 100배로 바뀜
}

/* 실행결과 (예: 3을 입력한 경우)
정수를 입력하시오:3

[값에 의한 호출]
호출 전 num=3
호출 후 num=3 (변경되지 않음)

[주소에 의한 호출]
호출 전 num=3
호출 후 num=300 (100배로 변경됨)
*/

/* 두 방식의 차이 및 원하는 결과
- 값에 의한 호출(multiply100_byValue) : 함수 호출시 num의 "값"만 복사되어
  전달되므로, 함수 내부에서 num을 100배로 만들어도 그것은 함수 안에서만
  존재하는 지역변수의 변화일 뿐이며 main함수의 num에는 전혀 반영되지 않음.
- 주소에 의한 호출(multiply100_byAddress) : num의 "주소"가 전달되므로
  포인터를 통해 main의 num이 저장된 메모리 공간을 직접 수정할 수 있음.
  따라서 함수 호출이 끝난 후에도 변경된 값(100배)이 그대로 유지됨.
- 우리가 원하는 결과(num을 실제로 100배로 바꾸는 것)를 얻으려면
  반드시 "주소에 의한 호출" 방식을 사용해야 함.
*/
