#define _CRT_SECURE_NO_WARNINGS
#pragma warning(disable:6031)
#include <stdio.h>

int main(void)
{
    // 2차원 배열 3개를 선언하고 초기화한다. (2행 2열 행렬)
    int a[2][2] = { {2, 4}, {5, -5} };    // 첫 번째 행렬
    int b[2][2] = { {-2, 3}, {0, -5} };   // 두 번째 행렬
    int c[2][2];                          // 덧셈 결과를 저장할 행렬
    int i, j;                             // i: 행 인덱스, j: 열 인덱스

    // [1] 배열 표현을 이용한 행렬 덧셈
    // 이중 반복문으로 같은 위치(i행 j열)의 원소끼리 더한다.
    for (i = 0; i < 2; i++)
    {
        for (j = 0; j < 2; j++)
        {
            c[i][j] = a[i][j] + b[i][j];
        }
    }

    printf("연산결과:\n");
    for (i = 0; i < 2; i++)
    {
        for (j = 0; j < 2; j++)
            printf("%d\t", c[i][j]);   // 한 행의 원소를 탭으로 구분하여 출력
        printf("\n");                  // 한 행을 출력하면 줄바꿈
    }

    // [2] 포인터 표현을 이용한 행렬 덧셈
    // a[i][j]는 *(*(a + i) + j)와 같다.
    //  - a + i      : i번째 행(1차원 배열)의 주소
    //  - *(a + i)   : i번째 행의 첫 번째 원소의 주소
    //  - *(a + i) + j : i행 j열 원소의 주소
    //  - *(*(a + i) + j) : i행 j열 원소의 값
    for (i = 0; i < 2; i++)
    {
        for (j = 0; j < 2; j++)
        {
            *(*(c + i) + j) = *(*(a + i) + j) + *(*(b + i) + j);
        }
    }

    printf("연산결과(포인터 표현):\n");
    for (i = 0; i < 2; i++)
    {
        for (j = 0; j < 2; j++)
            printf("%d\t", *(*(c + i) + j));
        printf("\n");
    }

    return 0;
}
