#define _CRT_SECURE_NO_WARNINGS
#pragma warning(disable:6031)
#include <stdio.h>

int main(void)
{
    // 행렬을 2차원 배열에 저장한다.
    int m[3][3] = {
        { -5,  2,  35},
        {-20,  5, 100},
        {-75,  5, -25}
    };
    int max = m[0][0];      // 첫 번째 원소를 일단 최대값으로 가정
    int row = 0, col = 0;   // 최대값의 위치 (인덱스, 0부터 시작)
    int i, j;

    // 이중 반복문으로 모든 원소를 검사한다.
    for (i = 0; i < 3; i++)
    {
        for (j = 0; j < 3; j++)
        {
            if (m[i][j] > max)  // 더 큰 값이 나오면
            {
                max = m[i][j];  // 최대값을 갱신하고
                row = i;        // 그 위치(행, 열)도 함께 저장한다.
                col = j;
            }
        }
    }

    // 인덱스는 0부터 시작하므로 출력할 때는 1을 더해 "몇 행 몇 열"로 나타낸다.
    printf("최대값은 %d\n", max);
    printf("위치는 %d행 %d열\n", row + 1, col + 1);

    return 0;
}
