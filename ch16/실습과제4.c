#define _CRT_SECURE_NO_WARNINGS
#pragma warning(disable:6031)
#include <stdio.h>

int main(void)
{
    char str[4][10];    // 문자열 4개를 저장하는 2차원 문자배열 (각 행이 문자열 1개)
    int len[4];         // 각 문자열의 길이
    int i, j;

    // 4개의 문자열을 입력받는다. (str[i]는 i번째 문자열의 시작 주소)
    for (i = 0; i < 4; i++)
    {
        printf("%d번째 문자열 입력: ", i + 1);
        scanf("%s", str[i]);
    }

    // strlen 같은 라이브러리 함수를 쓰지 않고 직접 길이를 센다.
    // 문자열의 끝은 널 문자('\0')이므로, '\0'을 만날 때까지 문자 수를 센다.
    for (i = 0; i < 4; i++)
    {
        j = 0;
        while (str[i][j] != '\0')
            j++;
        len[i] = j;     // '\0'을 만난 시점의 j가 문자열의 길이
    }

    for (i = 0; i < 4; i++)
        printf("%d번째 문자열 길이: %d\n", i + 1, len[i]);

    return 0;
}
