#define _CRT_SECURE_NO_WARNINGS
#pragma warning(disable:6031)
#include <stdio.h>

int main(void)
{
    char str[4][10];    // 문자열 4개를 저장하는 2차원 문자배열
    int last = 0;       // 사전에서 가장 뒤에 나오는 문자열의 인덱스 (첫 번째로 가정)
    int i;

    // 4개의 문자열을 입력받는다.
    for (i = 0; i < 4; i++)
    {
        printf("%d번째 문자열 입력: ", i + 1);
        scanf("%s", str[i]);
    }

    // strcmp 같은 라이브러리 함수를 쓰지 않고 첫 문자만 비교한다.
    // 문자는 아스키코드 값으로 비교되며, 알파벳은 사전 순서대로 값이 커진다.
    // 따라서 첫 문자의 값이 가장 큰 문자열이 사전에서 제일 뒤에 나온다.
    for (i = 1; i < 4; i++)
    {
        if (str[i][0] > str[last][0])
            last = i;
    }

    printf("사전에서 제일 뒤에 나오는 문자열: %s\n", str[last]);

    return 0;
}
