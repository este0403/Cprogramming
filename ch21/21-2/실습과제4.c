#define _CRT_SECURE_NO_WARNINGS
#pragma warning(disable:6031)
#include <stdio.h>

int main(void)
{
    char str[20];
    int i;

    printf("문자열입력:");
    fgets(str, sizeof(str), stdin);   // 엔터키('\n')까지 배열에 저장된다.

    // 배열에서 '\n'을 널문자('\0')로 변환
    // 처음부터 널문자를 만나기 전까지 검사하여 '\n'을 찾으면 '\0'으로 바꾸고 종료한다.
    // (입력이 배열 크기보다 길어서 '\n'이 저장되지 않은 경우에는 바꿀 문자가 없으므로 그대로 둔다.)
    for (i = 0; str[i] != '\0'; i++)
    {
        if (str[i] == '\n')
        {
            str[i] = '\0';            // 엔터키를 널문자로 변경 -> 문자열이 여기서 끝남
            break;
        }
    }

    printf("%s", str);                // 줄바꿈 없이 "hello"만 출력됨
    return 0;
}
