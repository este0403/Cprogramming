#define _CRT_SECURE_NO_WARNINGS
#pragma warning(disable:6031)
#include <stdio.h>

int main(void)
{
    char str[100];     // 공백을 포함한 문자열을 저장할 배열
    int i;
    int count = 0;     // 단어 수
    int inWord = 0;    // 현재 단어 안에 있으면 1, 공백 구간이면 0

    printf("문자열입력: ");
    fgets(str, sizeof(str), stdin);   // 공백을 포함한 문자열 입력 (엔터키도 함께 저장됨)

    // 문자열을 처음부터 널문자까지 한 글자씩 검사한다.
    // 공백(' ')이 아닌 문자가 새로 시작될 때마다 단어가 하나 시작된 것으로 센다.
    // 이렇게 하면 공백이 여러 개 연속되거나 앞뒤에 있어도 단어 수가 정확하다.
    for (i = 0; str[i] != '\0'; i++)
    {
        if (str[i] == ' ' || str[i] == '\n')   // 공백 또는 엔터키는 단어를 구분하는 문자
        {
            inWord = 0;                        // 단어가 끝남
        }
        else if (inWord == 0)                  // 공백 다음에 일반 문자가 처음 나온 경우
        {
            inWord = 1;                        // 새 단어 시작
            count++;                           // 단어 수 증가
        }
    }

    printf("단어수 : %d\n", count);
    return 0;
}
