#define _CRT_SECURE_NO_WARNINGS
#pragma warning(disable:6031)
#include <stdio.h>

int main(void)
{
	char ch;

	// 무한 루프: 'q' 또는 'Q'가 입력될 때까지 계속 반복
	while (1)
	{
		printf("문자입력 : ");

		// %c 앞에 공백을 넣으면 입력 버퍼에 남아있는 whitespace('\n' 등)를
		// 읽어서 버리고, whitespace가 아닌 문자 하나만 ch에 저장한다.
		// (공백이 없으면 이전 입력의 엔터키('\n')가 ch에 저장되어 버린다)
		scanf(" %c", &ch);

		// 종료 조건: 'q' 또는 'Q'가 입력되면 반복문을 빠져나감
		if (ch == 'q' || ch == 'Q')
			break;

		// 종료 문자가 아니면 입력된 문자를 출력
		printf("입력된 문자는 %c\n", ch);
	}

	return 0;
}
