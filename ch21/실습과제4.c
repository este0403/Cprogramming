#define _CRT_SECURE_NO_WARNINGS
#pragma warning(disable:6031)
#include <stdio.h>

// 실행 결과 설명은 README.md의 실습과제4 (반복문 단계별 버퍼 그림) 참고
int main(void)
{
	char ch;
	int i;

	for (i = 0; i < 5; i++)
	{
		printf("문자 입력:");

		// i = 0 : 버퍼가 비어 있으므로 입력을 기다림 -> "abcde<엔터>" 입력
		//         버퍼: a b c d e \n  중 'a'만 읽어 ch에 저장
		// i = 1~4 : 버퍼에 문자가 남아 있으므로 입력을 기다리지 않고
		//           'b', 'c', 'd', 'e'를 차례로 바로 읽음
		// 반복이 끝난 뒤 버퍼에는 엔터키('\n') 하나가 남는다.
		scanf("%c", &ch);

		printf("문자: %c\n", ch);
	}

	return 0;
}
